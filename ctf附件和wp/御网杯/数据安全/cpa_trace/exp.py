"""
将 plaintexts.npy、traces.npy、flag.enc 放在本脚本同目录下
依赖：numpy, pycryptodome
"""

import numpy as np
from Crypto.Cipher import AES
import os


# 1. 加载数据 - 支持相对路径

# 确定数据文件所在目录
script_dir = os.path.dirname(os.path.abspath(__file__))
data_dir = os.path.join(script_dir, "extracted", "tempdir", "CRYPTO附件", "inner", "附件")

# 如果相对路径不存在，尝试直接使用脚本目录
if not os.path.exists(os.path.join(data_dir, 'plaintexts.npy')):
    data_dir = script_dir  # 从 exp.py 同目录加载

# 如果还找不到，尝试当前工作目录
if not os.path.exists(os.path.join(data_dir, 'plaintexts.npy')):
    data_dir = "."

print(f"[*] 数据目录: {os.path.abspath(data_dir)}")
print("[*] 加载挑战数据...")
plaintexts = np.load(os.path.join(data_dir, 'plaintexts.npy'))      # (5000, 16) uint8
traces = np.load(os.path.join(data_dir, 'traces.npy'))              # (5000, 2, 1024) float64
with open(os.path.join(data_dir, 'flag.enc'), 'rb') as f:
    ct = f.read()  # 48 bytes

N, C, T = traces.shape
trace_power = traces[:, 0, :]  # 使用功耗通道

SBOX = np.array([
    0x63,0x7c,0x77,0x7b,0xf2,0x6b,0x6f,0xc5,0x30,0x01,0x67,0x2b,0xfe,0xd7,0xab,0x76,
    0xca,0x82,0xc9,0x7d,0xfa,0x59,0x47,0xf0,0xad,0xd4,0xa2,0xaf,0x9c,0xa4,0x72,0xc0,
    0xb7,0xfd,0x93,0x26,0x36,0x3f,0xf7,0xcc,0x34,0xa5,0xe5,0xf1,0x71,0xd8,0x31,0x15,
    0x04,0xc7,0x23,0xc3,0x18,0x96,0x05,0x9a,0x07,0x12,0x80,0xe2,0xeb,0x27,0xb2,0x75,
    0x09,0x83,0x2c,0x1a,0x1b,0x6e,0x5a,0xa0,0x52,0x3b,0xd6,0xb3,0x29,0xe3,0x2f,0x84,
    0x53,0xd1,0x00,0xed,0x20,0xfc,0xb1,0x5b,0x6a,0xcb,0xbe,0x39,0x4a,0x4c,0x58,0xcf,
    0xd0,0xef,0xaa,0xfb,0x43,0x4d,0x33,0x85,0x45,0xf9,0x02,0x7f,0x50,0x3c,0x9f,0xa8,
    0x51,0xa3,0x40,0x8f,0x92,0x9d,0x38,0xf5,0xbc,0xb6,0xda,0x21,0x10,0xff,0xf3,0xd2,
    0xcd,0x0c,0x13,0xec,0x5f,0x97,0x44,0x17,0xc4,0xa7,0x7e,0x3d,0x64,0x5d,0x19,0x73,
    0x60,0x81,0x4f,0xdc,0x22,0x2a,0x90,0x88,0x46,0xee,0xb8,0x14,0xde,0x5e,0x0b,0xdb,
    0xe0,0x32,0x3a,0x0a,0x49,0x06,0x24,0x5c,0xc2,0xd3,0xac,0x62,0x91,0x95,0xe4,0x79,
    0xe7,0xc8,0x37,0x6d,0x8d,0xd5,0x4e,0xa9,0x6c,0x56,0xf4,0xea,0x65,0x7a,0xae,0x08,
    0xba,0x78,0x25,0x2e,0x1c,0xa6,0xb4,0xc6,0xe8,0xdd,0x74,0x1f,0x4b,0xbd,0x8b,0x8a,
    0x70,0x3e,0xb5,0x66,0x48,0x03,0xf6,0x0e,0x61,0x35,0x57,0xb9,0x86,0xc1,0x1d,0x9e,
    0xe1,0xf8,0x98,0x11,0x69,0xd9,0x8e,0x94,0x9b,0x1e,0x87,0xe9,0xce,0x55,0x28,0xdf,
    0x8c,0xa1,0x89,0x0d,0xbf,0xe6,0x42,0x68,0x41,0x99,0x2d,0x0f,0xb0,0x54,0xbb,0x16
], dtype=np.uint8)


print("执行 CPA（汉明距离模型）...")
trace_centered = trace_power - trace_power.mean(axis=0)

master_key = []
for byte_pos in range(16):
    pt_byte = plaintexts[:, byte_pos]

    # 16 个相关峰在 1024 个采样点中等间距分布，间距 64
    # 第 i 字节的相关峰位于 t = 32 + 64*i
    t_center = 32 + 64 * byte_pos
    t_start = max(0, t_center - 5)
    t_end = min(T, t_center + 6)
    tw = trace_centered[:, t_start:t_end]
    tw = tw - tw.mean(axis=0)

    best_corr = -1
    best_key = -1

    for key_guess in range(256):
        # 汉明距离模型：计算 HD(plaintext, SBOX[plaintext XOR key_guess])
        hd = np.array([
            bin(int(p ^ SBOX[p ^ key_guess])).count('1')
            for p in pt_byte
        ], dtype=np.float64)
        hd -= hd.mean()

        # Pearson 相关系数
        cov = hd @ tw
        denom = np.linalg.norm(hd) * np.linalg.norm(tw, axis=0)
        corr = np.abs(cov / denom)
        max_corr = corr.max()

        if max_corr > best_corr:
            best_corr = max_corr
            best_key = key_guess

    master_key.append(int(best_key))
    print(f"字节 {byte_pos:2d}: 0x{best_key:02x}  相关性 = {best_corr:.5f}")

master_key = bytes(master_key)
print(f"\nAES-128 主密钥: {master_key.hex()}")

print("推导第 10 轮轮密钥...")

RCON = [0x01, 0x02, 0x04, 0x08, 0x10, 0x20, 0x40, 0x80, 0x1b, 0x36]
SBOX_LIST = list(SBOX)

# 密钥扩展
w = [[master_key[4*i + j] for j in range(4)] for i in range(4)]
for i in range(4, 44):
    temp = w[i - 1][:]
    if i % 4 == 0:
        # RotWord
        temp = [temp[1], temp[2], temp[3], temp[0]]
        # SubWord
        temp = [SBOX_LIST[t] for t in temp]
        # XOR RCON
        temp[0] ^= RCON[i // 4 - 1]
    w.append([w[i - 4][j] ^ temp[j] for j in range(4)])

# 提取所有轮密钥
round_keys = []
for r in range(11):
    rk = bytes(sum((w[r * 4 + j] for j in range(4)), []))
    round_keys.append(rk)
    if r in [0, 10]:
        print(f"    第 {r:2d} 轮密钥: {rk.hex()}")

round_10_key = round_keys[10]
print(f"\n第 10 轮轮密钥: {round_10_key.hex()}")


print("解密 flag.enc...")

cipher = AES.new(round_10_key, AES.MODE_ECB)
flag_padded = cipher.decrypt(ct)

# 去除 PKCS7 填充
pad_len = flag_padded[-1]
flag = flag_padded[:-pad_len].decode('utf-8')

print(f"\nFlag: {flag}")
print(f"Flag (hex): {flag_padded.hex()}")
