def cpa_attack(trace_data, pt_byte, model_fn):
    hw_all = np.zeros((256, N), dtype=np.float64)
    for kg in range(256):
        hw = model_fn(pt_byte, kg)
        hw_all[kg] = hw - hw.mean()

    trace_centered = trace_data - trace_data.mean(axis=0)
    cov = hw_all @ trace_centered
    norm_hw = np.linalg.norm(hw_all, axis=1)
    norm_trace = np.linalg.norm(trace_centered, axis=0)
    corr = np.abs(cov) / (norm_hw[:, np.newaxis] * norm_trace[np.newaxis, :])
    max_corr_per_key = corr.max(axis=1)
    best_key = max_corr_per_key.argmax()
    best_corr = max_corr_per_key[best_key]
    best_time = corr[best_key].argmax()
    return best_key, best_corr, best_time, max_corr_per_key, corr

